#!/usr/bin/env bash
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CONFIG_PATH="$REPO_ROOT/.cargo/config.toml"
mkdir -p "$REPO_ROOT/.cargo"

SCCACHE_BIN="$(command -v sccache || true)"
MOLD_BIN="$(command -v mold || true)"
LLD_BIN="$(command -v lld || true)"

{
    echo "# Machine-local Cargo settings (gitignored). Generated by scripts/setup-rust.sh."
    echo ""
    echo "[build]"
    if [[ -n "$SCCACHE_BIN" ]]; then
        echo "rustc-wrapper = \"$SCCACHE_BIN\""
    else
        echo "# sccache not found; install sccache and re-run scripts/setup-rust.sh"
    fi
    echo ""
    if [[ "$(uname -s)" == "Linux" ]]; then
        echo "[target.x86_64-unknown-linux-gnu]"
        if [[ -n "$MOLD_BIN" ]]; then
            echo 'linker = "clang"'
            echo 'rustflags = ["-C", "link-arg=-fuse-ld=mold"]'
        elif [[ -n "$LLD_BIN" ]]; then
            echo 'linker = "clang"'
            echo 'rustflags = ["-C", "link-arg=-fuse-ld=lld"]'
        fi
        echo ""
    fi
    echo "[net]"
    echo "retry = 2"
} > "$CONFIG_PATH"

echo "Wrote $CONFIG_PATH (sccache=${SCCACHE_BIN:-none}, mold=${MOLD_BIN:-none}, lld=${LLD_BIN:-none})"
