<#
.SYNOPSIS
    Generates machine-local .cargo/config.toml with sccache and rust-lld for fast Rust builds.
.DESCRIPTION
    Auto-detects sccache (PATH or E:/Development/_tools/sccache) and writes .cargo/config.toml
    (gitignored) so plain `cargo build` / `cargo test` is cached and fast with no PATH edits.
#>
[CmdletBinding()]
param(
    [string]$TargetDir = "",
    [string]$SccacheDir = "E:/sccache",
    [string]$SccacheSize = "50G",
    [int]$Jobs = 0,
    [switch]$EnableRustSccache
)

$ErrorActionPreference = "Stop"
$repoRoot = (Resolve-Path (Join-Path $PSScriptRoot "..")).Path
$cargoDir = Join-Path $repoRoot ".cargo"
$configPath = Join-Path $cargoDir "config.toml"

New-Item -ItemType Directory -Force -Path $cargoDir | Out-Null

# Locate sccache: PATH first, then local _tools directory.
$sccachePath = $null
$inPath = Get-Command sccache -ErrorAction SilentlyContinue
if ($inPath) {
    $sccachePath = $inPath.Source -replace '\\', '/'
} elseif (Test-Path "E:/Development/_tools/sccache") {
    $found = Get-ChildItem "E:/Development/_tools/sccache" -Recurse -Filter "sccache.exe" -ErrorAction SilentlyContinue |
        Sort-Object FullName -Descending |
        Select-Object -First 1
    if ($found) {
        $sccachePath = $found.FullName -replace '\\', '/'
    }
}

if (-not $TargetDir -and (Test-Path "E:/Development/_cache")) {
    $TargetDir = "E:/Development/_cache/cargo-target/zerohour-reloaded"
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add("# Machine-local Cargo settings (gitignored). Generated by scripts/setup-rust.ps1.")
$lines.Add("")
$lines.Add("[build]")
if ($sccachePath -and $EnableRustSccache) {
    $lines.Add("rustc-wrapper = `"$sccachePath`"")
} elseif ($sccachePath) {
    $lines.Add("# sccache rustc-wrapper disabled by default on Windows (use -EnableRustSccache to opt in; C++ builds still use sccache)")
} else {
    $lines.Add("# sccache not found; install sccache and re-run scripts/setup-rust.ps1")
}
if ($TargetDir) {
    $normTarget = $TargetDir -replace '\\', '/'
    $lines.Add("target-dir = `"$normTarget`"")
}
if ($Jobs -gt 0) {
    $lines.Add("jobs = $Jobs")
}
$lines.Add("")

if ($sccachePath) {
    $lines.Add("[env]")
    if (Test-Path (Split-Path $SccacheDir -Qualifier) -ErrorAction SilentlyContinue) {
        $normCache = $SccacheDir -replace '\\', '/'
        $lines.Add("SCCACHE_DIR = { value = `"$normCache`", force = true }")
    }
    $lines.Add("SCCACHE_CACHE_SIZE = { value = `"$SccacheSize`", force = true }")
    $lines.Add("")
}

$lines.Add("[target.x86_64-pc-windows-msvc]")
$lines.Add('linker = "rust-lld.exe"')
$lines.Add("")
$lines.Add("[target.aarch64-pc-windows-msvc]")
$lines.Add('linker = "rust-lld.exe"')
$lines.Add("")
$lines.Add("[net]")
$lines.Add("retry = 2")

Set-Content -Path $configPath -Value ($lines -join "`n") -Encoding UTF8
Write-Host "Wrote $configPath"
if ($sccachePath) {
    Write-Host "  sccache   : $sccachePath"
    Write-Host "  cache dir : $SccacheDir ($SccacheSize)"
} else {
    Write-Warning "sccache not found (install via 'winget install Mozilla.sccache' or 'cargo install sccache')"
}
if ($TargetDir) {
    Write-Host "  target-dir: $TargetDir"
}
Write-Host "  linker    : rust-lld.exe"
